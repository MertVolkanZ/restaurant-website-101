function updateLanguageFlag(lang) {

    const desktopSelect =
        document.getElementById("language-switch");

    const mobileSelect =
        document.getElementById("mobile-language-switch");

    const flag =
        flagMap[lang];


    if (desktopSelect) {

        if (flag) {
            desktopSelect.style.backgroundImage =
                `url("${flag}")`;
        }
        else {
            desktopSelect.style.backgroundImage =
                "none";
        }

    }


    if (mobileSelect) {

        if (flag) {
            mobileSelect.style.backgroundImage =
                `url("${flag}")`;
        }
        else {
            mobileSelect.style.backgroundImage =
                "none";
        }

    }

}
function applyLanguage(lang) {

    const selectedLanguage = translations[lang];

    if (!selectedLanguage) {
        return;
    }


    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.getAttribute("data-i18n");

            if (selectedLanguage[key]) {
                element.textContent =
                    selectedLanguage[key];
            }

        });


    document.documentElement.lang = lang;

    document.documentElement.dir =
        lang === "ar" ? "rtl" : "ltr";


    updateLanguageFlag(lang);
    renderEditorialContent(lang);

}
function initLanguageSettings() {

    const desktopSelect =
        document.getElementById("language-switch");

    const mobileSelect =
        document.getElementById("mobile-language-switch");


    const savedLanguage =
        localStorage.getItem("language") || "tr";


    if (desktopSelect) {
        desktopSelect.value = savedLanguage;
    }

    if (mobileSelect) {
        mobileSelect.value = savedLanguage;
    }


    applyLanguage(savedLanguage);


    if (desktopSelect) {

        desktopSelect.addEventListener(
            "change",
            function () {

                const selected =
                    this.value;

                localStorage.setItem(
                    "language",
                    selected
                );


                if (mobileSelect) {
                    mobileSelect.value = selected;
                }


                applyLanguage(selected);

            }
        );

    }


    if (mobileSelect) {

        mobileSelect.addEventListener(
            "change",
            function () {

                const selected =
                    this.value;

                localStorage.setItem(
                    "language",
                    selected
                );


                if (desktopSelect) {
                    desktopSelect.value = selected;
                }


                applyLanguage(selected);

            }
        );

    }

}



