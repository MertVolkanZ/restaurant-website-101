function renderEditorialContent(lang) {
    const story = storyContent[lang] || storyContent.tr;
    document.querySelectorAll('[data-story]').forEach(element => {
        const value = story[element.dataset.story];
        if (typeof value === 'string') element.textContent = value;
    });
    document.querySelectorAll('[data-featured-index]').forEach(element => {
        const index = Number(element.dataset.featuredIndex);
        element.textContent = story.featuredQuotes?.[index] || '';
    });
    document.querySelectorAll('[data-dish-index]').forEach(element => {
        const index = Number(element.dataset.dishIndex);
        element.textContent = story.dishTexts?.[index] || '';
    });
    const highlights = document.getElementById('about-highlights');
    if (highlights) {
        highlights.replaceChildren(...(story.aboutHighlights || []).map(label => {
            const span = document.createElement('span');
            span.textContent = label;
            return span;
        }));
    }
}
